//! What silva does around one job, as bash, for every export target: stage
//! `inputs/`, run `pre`/`run`/`post`, collect `outputs/`.
//!
//! The host language provides three things: the job folder at [`JOB_DIR`],
//! each dependency's output folder as a positional argument, and, for a
//! dependency-free job, `input_files/` at [`INPUT_FILES`]. The driver uses no
//! `$(`, `${`, `~{` or `>>>` of its own, so each target escapes only user text.

use super::ir::ExportJob;

/// Inside a step's working folder. Hidden, so no job name can collide with them.
pub const JOB_DIR: &str = ".silva_job";
pub const INPUT_FILES: &str = ".silva_input_files";

/// A CWL identifier for a job or param name; also the job's output folder.
pub fn id(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' || c == '-' {
                c
            } else {
                '_'
            }
        })
        .collect()
}

fn sh_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', "'\\''"))
}

/// A name pattern as a `case` alternative: glob characters stay live, the rest literal.
fn case_pattern(pattern: &str) -> String {
    pattern
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || "*?[]!^-._,/+=:@%~".contains(c) {
                c.to_string()
            } else {
                format!("\\{c}")
            }
        })
        .collect()
}

/// What silva does around one job, as bash. Written without `$(` or `${`, so
/// nothing in it needs escaping for CWL.
pub fn driver(job: &ExportJob) -> String {
    let mut s = String::from(
        "# Generated by silva export: stages inputs/, runs the job, collects outputs/.\n",
    );
    s.push_str("set -eu\n");
    s.push_str(&format!("mkdir -p {JOB_DIR}/inputs\n"));

    if job.takes_input_files {
        s.push_str(&format!(
            "# Dependency-free: the workflow's input_files/, everything in it.\n\
             cp -r {INPUT_FILES}/. {JOB_DIR}/inputs/\n"
        ));
    }

    if !job.dependencies.is_empty() {
        s.push_str(
            "# Each dependency's outputs/, in [dependencies] order; the first of a name wins.\n",
        );
        if job.inputs.is_empty() {
            s.push_str("wanted() { return 0; }\n");
        } else {
            let alternatives: Vec<String> = job.inputs.iter().map(|p| case_pattern(p)).collect();
            s.push_str(&format!(
                "wanted() {{\n  case \"$1\" in\n    {}) return 0 ;;\n  esac\n  return 1\n}}\n",
                alternatives.join("|")
            ));
        }
        s.push_str(&format!(
            "for src in \"$@\"; do\n\
             \x20 for f in \"$src\"/* \"$src\"/.[!.]* \"$src\"/..?*; do\n\
             \x20   [ -e \"$f\" ] || continue\n\
             \x20   n=`basename \"$f\"`\n\
             \x20   wanted \"$n\" || continue\n\
             \x20   if [ -e \"{JOB_DIR}/inputs/$n\" ]; then\n\
             \x20     echo \"Warning: File '$n' already copied, skipping\" >&2\n\
             \x20     continue\n\
             \x20   fi\n\
             \x20   cp -r \"$f\" \"{JOB_DIR}/inputs/$n\"\n\
             \x20 done\n\
             done\n"
        ));
    }

    s.push_str(&format!("cd {JOB_DIR}\n"));
    for script in &job.scripts {
        s.push_str(&format!(
            "sed 's/\\r$//' {} | /bin/bash -s\n",
            sh_quote(script)
        ));
    }

    s.push_str("mkdir -p outputs\n");
    if !job.outputs.is_empty() {
        s.push_str("# outputs patterns are evaluated by bash, as silva evaluates them.\nshopt -s nullglob\n");
        for pattern in &job.outputs {
            s.push_str(&format!(
                "for f in {pattern}; do cp -r \"$f\" outputs/ || echo \"Warning: Failed to copy $f\" >&2; done\n"
            ));
        }
    }
    s.push_str(&format!("mv outputs ../{}\n", id(&job.name)));
    s
}
